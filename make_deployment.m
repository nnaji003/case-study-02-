function D = make_deployment(seed)
%MAKE_DEPLOYMENT  Generate a random robot-swarm deployment (ESE 105, Case Study II).
%
%   D = make_deployment(seed) returns one deployment as a struct with fields
%
%       D.G       150x150 adjacency matrix (symmetric, 0/1, zero diagonal)
%       D.P0      150x2 landing positions; row i is robot i's (x, y)
%       D.r       radio range used to build G
%       D.faulty  column vector of indices of robots with broken drives
%       D.g       1x2 rally point
%       D.seed    the seed used
%
%   Each seed gives a different deployment; the same seed always gives the
%   same deployment. Deployments have these features:
%     - 150 robots dropped into 2 to 4 square zones (side length 3 to 5),
%       each holding at least 10 robots, separated by gaps;
%     - a radio range just large enough that the whole swarm is connected;
%     - 2 to 5 faulty robots, all in one zone;
%     - a rally point somewhere in the region covered by the robots.
%
%   The competition's hidden deployments are generated by this same
%   function, using seeds that are not released.
%
%   Note: G is built from P0 and r. Your own make_disk(D.P0, D.r) should
%   reproduce D.G exactly, which makes a useful test of your code.

n = 150;

% Use the requested seed without disturbing the caller's random state.
oldState = rng;
rng(seed, 'twister');
cleanup = onCleanup(@() rng(oldState));

% ---- zones: how many, how big, and how many robots in each ----
nz = randi([2 4]);
side = 3 + 2*rand(nz, 1);
sizes = 10*ones(nz, 1) + accumarray(randi(nz, n - 10*nz, 1), 1, [nz 1]);

% ---- zone centers: each new zone sits a gap away from an existing one ----
centers = zeros(nz, 2);
for z = 2:nz
    for attempt = 1:200
        ang  = 2*pi*rand;
        base = centers(randi(z - 1), :);
        dist = side(z) + 1.5 + 1.5*rand;
        c = base + dist*[cos(ang) sin(ang)];
        gaps = sqrt(sum((centers(1:z-1, :) - c).^2, 2));
        if all(gaps > max(side) + 1)
            break
        end
    end
    centers(z, :) = c;
end

% ---- robot positions: uniform within each zone ----
P0 = zeros(n, 2);
zone = zeros(n, 1);
idx = 0;
for z = 1:nz
    rows = idx + (1:sizes(z));
    P0(rows, :) = centers(z, :) + (rand(sizes(z), 2) - 0.5)*side(z);
    zone(rows) = z;
    idx = idx + sizes(z);
end

% ---- radio range: smallest multiple of 0.1 that connects the swarm, plus 0.1 ----
D2 = (P0(:,1) - P0(:,1)').^2 + (P0(:,2) - P0(:,2)').^2;   % squared distances
r = 0.8;
while ~is_connected(range_graph(D2, r))
    r = round(r + 0.1, 1);
end
r = round(r + 0.1, 1);
G = range_graph(D2, r);

% ---- faulty robots: 2 to 5, all in one randomly chosen zone ----
fz = randi(nz);
inZone = find(zone == fz);
nf = randi([2 5]);
faulty = inZone(randperm(numel(inZone), nf));
faulty = faulty(:);

% ---- rally point: uniform in the bounding box of the robots ----
lo = min(P0, [], 1);
hi = max(P0, [], 1);
g = lo + rand(1, 2).*(hi - lo);

D = struct('G', G, 'P0', P0, 'r', r, 'faulty', faulty, 'g', g, 'seed', seed);
end

